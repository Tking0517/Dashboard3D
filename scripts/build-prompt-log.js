#!/usr/bin/env node
// Walks a Claude Code session JSONL transcript, extracts every user prompt
// (skipping tool results, system reminders, ide_opened_file tags), and pairs
// each prompt with the cumulative token usage of all assistant responses
// that followed it (until the next user prompt).
//
// Usage:  node scripts/build-prompt-log.js <transcript.jsonl> [output.md]

'use strict';
const fs = require('fs');
const path = require('path');

const SRC = process.argv[2] || 'C:\\Users\\tho-m\\.claude\\projects\\d--AI-REPO-TEST\\2b962f0d-cb68-4ce0-a6de-60410ee9806e.jsonl';
const OUT = process.argv[3] || path.join(__dirname, '..', 'PROMPT-LOG.md');

if (!fs.existsSync(SRC)) {
  console.error('transcript not found:', SRC);
  process.exit(1);
}

// Strip <system-reminder>…</system-reminder> blocks and similar wrapping tags
// so we record only what the human actually wrote.
function cleanPromptText(s) {
  return s
    .replace(/<system-reminder>[\s\S]*?<\/system-reminder>/g, '')
    .replace(/<ide_opened_file>[\s\S]*?<\/ide_opened_file>/g, '')
    .replace(/<ide_selection>[\s\S]*?<\/ide_selection>/g, '')
    .replace(/<command-message>[\s\S]*?<\/command-message>/g, '')
    .replace(/<command-name>[\s\S]*?<\/command-name>/g, '')
    .replace(/<local-command-stdout>[\s\S]*?<\/local-command-stdout>/g, '')
    .replace(/<local-command-stderr>[\s\S]*?<\/local-command-stderr>/g, '')
    .replace(/<bash-input>[\s\S]*?<\/bash-input>/g, '')
    .replace(/<bash-stdout>[\s\S]*?<\/bash-stdout>/g, '')
    .replace(/<bash-stderr>[\s\S]*?<\/bash-stderr>/g, '')
    .trim();
}

const prompts = [];
let current = null; // active prompt accumulator

const lines = fs.readFileSync(SRC, 'utf8').split('\n');
for (const line of lines) {
  if (!line.trim()) continue;
  let obj;
  try { obj = JSON.parse(line); } catch { continue; }
  if (obj.type !== 'user' && obj.type !== 'assistant') continue;

  if (obj.type === 'user' && obj.message?.role === 'user') {
    const blocks = Array.isArray(obj.message.content) ? obj.message.content : [];
    // Real prompt = at least one text block (not just tool_result).
    const textParts = blocks
      .filter(b => b.type === 'text' && typeof b.text === 'string')
      .map(b => cleanPromptText(b.text))
      .filter(Boolean);
    if (textParts.length === 0) continue;
    if (current) prompts.push(current);
    current = {
      timestamp: obj.timestamp || '',
      text: textParts.join('\n').trim(),
      input: 0,
      output: 0,
      cacheRead: 0,
      cacheCreation: 0,
      assistantTurns: 0,
    };
    continue;
  }

  if (obj.type === 'assistant' && current) {
    const u = obj.message?.usage;
    if (u) {
      current.input         += u.input_tokens || 0;
      current.output        += u.output_tokens || 0;
      current.cacheRead     += u.cache_read_input_tokens || 0;
      current.cacheCreation += u.cache_creation_input_tokens || 0;
      current.assistantTurns += 1;
    }
  }
}
if (current) prompts.push(current);

// Build the markdown.
const totals = prompts.reduce((a, p) => ({
  input:         a.input         + p.input,
  output:        a.output        + p.output,
  cacheRead:     a.cacheRead     + p.cacheRead,
  cacheCreation: a.cacheCreation + p.cacheCreation,
}), { input: 0, output: 0, cacheRead: 0, cacheCreation: 0 });

const fmt = (n) => n.toLocaleString('en-US');
const truncate = (s, n) => s.length > n ? s.slice(0, n).trimEnd() + '…' : s;

let md = `# Dashboard3D — Prompt & Token Log\n\n`;
md += `Generated from session transcript: \`${path.basename(SRC)}\`\n\n`;
md += `**Total prompts:** ${prompts.length}  \n`;
md += `**Total input tokens:** ${fmt(totals.input)}  \n`;
md += `**Total output tokens:** ${fmt(totals.output)}  \n`;
md += `**Total cache read:** ${fmt(totals.cacheRead)}  \n`;
md += `**Total cache creation:** ${fmt(totals.cacheCreation)}  \n`;
md += `**Grand total tokens:** ${fmt(totals.input + totals.output + totals.cacheRead + totals.cacheCreation)}\n\n`;

md += `## How to read this\n\n`;
md += `Each row is one user prompt and the cumulative token usage of every assistant turn it triggered (a single prompt can span many internal tool-use turns).\n\n`;
md += `- **input** = new prompt tokens sent\n`;
md += `- **output** = tokens generated by the assistant\n`;
md += `- **cacheRead** = tokens read from prompt cache (cheap)\n`;
md += `- **cacheCreation** = tokens written to prompt cache (one-time)\n\n`;

md += `## Summary table\n\n`;
md += `| # | Time | Turns | Input | Output | Cache Read | Cache Create | Prompt |\n`;
md += `|---|------|-------|------:|-------:|-----------:|-------------:|--------|\n`;
prompts.forEach((p, i) => {
  const t = p.timestamp ? p.timestamp.slice(0, 19).replace('T', ' ') : '';
  const text = truncate(p.text.replace(/\|/g, '\\|').replace(/\n/g, ' '), 90);
  md += `| ${i + 1} | ${t} | ${p.assistantTurns} | ${fmt(p.input)} | ${fmt(p.output)} | ${fmt(p.cacheRead)} | ${fmt(p.cacheCreation)} | ${text} |\n`;
});
md += `\n## Full prompts\n\n`;
prompts.forEach((p, i) => {
  md += `### ${i + 1}. ${p.timestamp ? p.timestamp.slice(0, 19).replace('T', ' ') : ''}\n\n`;
  md += `**Tokens** — in: ${fmt(p.input)} · out: ${fmt(p.output)} · cache read: ${fmt(p.cacheRead)} · cache create: ${fmt(p.cacheCreation)} · turns: ${p.assistantTurns}\n\n`;
  md += `> ${p.text.split('\n').join('\n> ')}\n\n`;
});

fs.writeFileSync(OUT, md);
console.log(`Wrote ${prompts.length} prompts to ${OUT}`);
